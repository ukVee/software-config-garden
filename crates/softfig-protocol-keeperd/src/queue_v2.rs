//! The queue v2 vocabularies that cross the keeperd wire. The rest of the state
//! model stays in `softfig_ipc::queue_v2`, which re-exports these.

use std::fmt;

use serde::{Deserialize, Serialize};

/// An entry's `kind` (§1, §3.1): one milestone, task or restack in the list.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum EntryKind {
    /// A milestone with `slices.toml` + `slices/` under `milestones/<id>/`.
    Milestone,
    /// A standalone unit: the doc at `tasks/NNN-<slug>.md` is the work.
    Task,
    /// A stack-repair run generated by growlightd (§8). Always urgent, no
    /// branch of its own.
    Restack,
}

/// An entry's `lane` (§2): the urgent lane always drains first.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Lane {
    Urgent,
    Normal,
}

/// A slice item's `status` (§3.3, §7): `split` means the remaining work moved
/// into a sub-milestone.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SliceStatus {
    Queued,
    Active,
    Done,
    Split,
    Blocked,
    Deferred,
}

// Each `Display` is exactly the TOML wire name, the name serde reads and writes.
// `wire_names` pins the lockstep.
impl fmt::Display for EntryKind {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::Milestone => "milestone",
            Self::Task => "task",
            Self::Restack => "restack",
        })
    }
}

impl fmt::Display for Lane {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::Urgent => "urgent",
            Self::Normal => "normal",
        })
    }
}

impl fmt::Display for SliceStatus {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::Queued => "queued",
            Self::Active => "active",
            Self::Done => "done",
            Self::Split => "split",
            Self::Blocked => "blocked",
            Self::Deferred => "deferred",
        })
    }
}

#[cfg(test)]
mod tests {
    use serde::de::DeserializeOwned;

    use super::*;

    fn assert_wire_name<T>(value: T, name: &str)
    where
        T: Copy + fmt::Debug + fmt::Display + PartialEq + Serialize + DeserializeOwned,
    {
        assert_eq!(value.to_string(), name);
        assert_eq!(serde_json::to_value(value).unwrap(), name);
        assert_eq!(serde_json::from_value::<T>(name.into()).unwrap(), value);
    }

    #[test]
    fn wire_names() {
        assert_wire_name(EntryKind::Milestone, "milestone");
        assert_wire_name(EntryKind::Task, "task");
        assert_wire_name(EntryKind::Restack, "restack");
        assert_wire_name(Lane::Urgent, "urgent");
        assert_wire_name(Lane::Normal, "normal");
        assert_wire_name(SliceStatus::Queued, "queued");
        assert_wire_name(SliceStatus::Active, "active");
        assert_wire_name(SliceStatus::Done, "done");
        assert_wire_name(SliceStatus::Split, "split");
        assert_wire_name(SliceStatus::Blocked, "blocked");
        assert_wire_name(SliceStatus::Deferred, "deferred");
    }
}
