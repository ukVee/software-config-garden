//! growlight Phase 2 — `softfig growlight init`, the pillar scaffolder.
//!
//! Idempotent retrofit (mirrors `migrate split`): materializes the `growlight/`
//! pillar via the same write/commit machinery as the Phase-1 MCP verbs, writes
//! the two embedded templates (`protocol.md`, `session-policy.md`), and performs
//! the spec §14 nav wiring (root `CLAUDE.md` top-level map + boundary row,
//! `meta/reserved-filenames.md`, `meta/conventions.md`). The garden/runtime
//! split is honoured: only the durable garden pillar is created here — the
//! churny runtime (`baton.md`, `usage.json`, `loop.json`, `questions.md` under
//! `$XDG_CONFIG_HOME/softfig/growlight/`) belongs to the Phase-2b launcher and
//! is written CLI-side, never committed.
//!
//! Everything folds into one `growlight_initialized` commit. A re-run on an
//! already-scaffolded garden creates nothing and makes no commit (no empty
//! commits) — only the missing pieces are filled, so the action is also
//! self-healing for a partially-built pillar.

